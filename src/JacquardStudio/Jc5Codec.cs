using System.Buffers.Binary;
using System.IO;
using System.Text;
using System.Windows.Media;
using System.Windows.Media.Imaging;

namespace JacquardStudio;

/// <summary>Experimental single-area JC5 subset observed in EAT OpenWeave exports, not a general JC5 specification.</summary>
public static class Jc5Codec
{
    private const int MaxPixels = 4_000_000;
    private const int MaxFileBytes = 8_000_000;
    private static readonly byte[] Magic = { 0x81, 0xfe, 0x01, 0x01 };

    private static void WriteNumber(Stream s, int value)
    {
        Span<byte> data = stackalloc byte[4];
        BinaryPrimitives.WriteInt32BigEndian(data, value); s.Write(data);
    }
    private static int ReadNumber(BinaryReader r)
    {
        byte[] data = r.ReadBytes(4);
        if (data.Length != 4) throw new InvalidDataException("Truncated JC5 header.");
        return BinaryPrimitives.ReadInt32BigEndian(data);
    }
    private static byte[] NullAscii(string text) => Encoding.ASCII.GetBytes(text + "\0");
    private static void Field(Stream s, int id, byte[] value)
    {
        WriteNumber(s, id); WriteNumber(s, value.Length); s.Write(value);
    }
    private static void NumberField(Stream s, int id, int value)
    {
        WriteNumber(s, id); WriteNumber(s, 4); WriteNumber(s, value);
    }
    private static byte[] ReadField(BinaryReader r, int id, int max)
    {
        if (ReadNumber(r) != id) throw new InvalidDataException("Unsupported JC5 header or field order.");
        int length = ReadNumber(r);
        if (length < 1 || length > max || length > r.BaseStream.Length - r.BaseStream.Position) throw new InvalidDataException("Invalid JC5 field length.");
        byte[] value = r.ReadBytes(length);
        return value;
    }
    private static int ReadNumberField(BinaryReader r, int id)
    {
        byte[] value = ReadField(r, id, 4);
        if (value.Length != 4) throw new InvalidDataException("Invalid JC5 numeric field.");
        return BinaryPrimitives.ReadInt32BigEndian(value);
    }
    private static void CheckText(byte[] data)
    {
        if (data[^1] != 0 || data.Take(data.Length - 1).Any(b => b < 32 || b > 126)) throw new InvalidDataException("Unsupported JC5 text encoding.");
    }
    private static void CheckDimensions(int width, int height)
    {
        if (width <= 0 || height <= 0 || (long)width * height > MaxPixels) throw new InvalidDataException("Invalid or unsupported JC5 dimensions (maximum 4 million pixels).");
    }
    public static byte[] Encode(BitmapSource image, string name)
    {
        int width = image.PixelWidth, height = image.PixelHeight; CheckDimensions(width, height);
        // The sampled controller name is ASCII and NUL-terminated. Do not silently encode Unicode as '?'.
        if (string.IsNullOrWhiteSpace(name) || name.Length > 120 || name.Any(c => c < 32 || c > 126))
            throw new ArgumentException("JC5 internal name must contain 1–120 printable ASCII characters.");
        var bgra = new FormatConvertedBitmap(image, PixelFormats.Bgra32, null, 0);
        int pixelsStride = checked(width * 4), rowBytes = (width + 7) / 8;
        byte[] pixels = new byte[checked(pixelsStride * height)]; bgra.CopyPixels(pixels, pixelsStride, 0);
        byte[] raster = new byte[checked(rowBytes * height)];
        for (int y = 0; y < height; y++)
        for (int x = 0; x < width; x++)
        {
            int p = y * pixelsStride + x * 4;
            if (pixels[p + 3] != 255 || pixels[p] != pixels[p + 1] || pixels[p] != pixels[p + 2] || (pixels[p] != 0 && pixels[p] != 255))
                throw new InvalidDataException("JC5 requires an opaque, pure black-and-white hook map. Assign every pattern first.");
            if (pixels[p] == 0) raster[(height - 1 - y) * rowBytes + x / 8] |= (byte)(0x80 >> (x % 8));
        }
        using var s = new MemoryStream(); s.Write(Magic);
        WriteNumber(s, 4); WriteNumber(s, 1); Field(s, 1, NullAscii(name)); NumberField(s, 2, height); NumberField(s, 6, 0);
        Field(s, 8, NullAscii("Generated by Jacquard Studio"));
        WriteNumber(s, 1); // one area
        byte[] areaName = NullAscii($"Area 1: {width} hooks");
        WriteNumber(s, 100); WriteNumber(s, checked(8 + areaName.Length)); WriteNumber(s, 1); WriteNumber(s, width); s.Write(areaName);
        s.Write(raster); return s.ToArray();
    }
    public static BitmapSource Decode(byte[] data)
    {
        if (data.Length > MaxFileBytes) throw new InvalidDataException("JC5 exceeds the supported size.");
        using var stream = new MemoryStream(data, false); using var r = new BinaryReader(stream);
        if (!r.ReadBytes(4).SequenceEqual(Magic) || ReadNumber(r) != 4 || ReadNumber(r) != 1) throw new InvalidDataException("Unsupported JC5 signature or version.");
        CheckText(ReadField(r, 1, 1024));
        int height = ReadNumberField(r, 2);
        if (ReadNumberField(r, 6) != 0) throw new InvalidDataException("Unsupported JC5 option.");
        CheckText(ReadField(r, 8, 4096));
        if (ReadNumber(r) != 1) throw new InvalidDataException("Only single-area JC5 files are supported.");
        byte[] area = ReadField(r, 100, 4096);
        if (area.Length < 9 || BinaryPrimitives.ReadInt32BigEndian(area) != 1) throw new InvalidDataException("Unsupported JC5 area.");
        int width = BinaryPrimitives.ReadInt32BigEndian(area.AsSpan(4)); CheckText(area[8..]); CheckDimensions(width, height);
        int rowBytes = (width + 7) / 8;
        if (stream.Length - stream.Position != (long)rowBytes * height) throw new InvalidDataException("Unexpected JC5 raster size or unsupported extra data.");
        byte[] raster = r.ReadBytes(rowBytes * height), pixels = new byte[width * height];
        for (int y = 0; y < height; y++)
        for (int x = 0; x < width; x++)
            pixels[y * width + x] = (raster[(height - 1 - y) * rowBytes + x / 8] & (0x80 >> (x % 8))) != 0 ? (byte)0 : (byte)255;
        // Only declared hooks are exposed; trailing bits in the last byte are not represented in the image.
        var image = BitmapSource.Create(width, height, 96, 96, PixelFormats.Gray8, null, pixels, width); image.Freeze(); return image;
    }
    public static BitmapSource Load(string path)
    {
        using var f = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read);
        if (f.Length > MaxFileBytes) throw new InvalidDataException("JC5 exceeds the supported size.");
        using var m = new MemoryStream(); f.CopyTo(m); return Decode(m.ToArray());
    }
    public static void Save(BitmapSource image, string target, IEnumerable<string> protectedPaths)
    {
        string destination = Path.GetFullPath(target);
        if (!Path.GetExtension(destination).Equals(".jc5", StringComparison.OrdinalIgnoreCase)) throw new ArgumentException("JC5 requires a .jc5 extension.");
        if (protectedPaths.Any(p => string.Equals(Path.GetFullPath(p), destination, StringComparison.OrdinalIgnoreCase))) throw new IOException("Cannot overwrite an input file, project, or pattern.");
        // Use a deterministic ASCII name rather than corrupting Persian file names in the JC5 header.
        byte[] data = Encode(image, "JacquardStudio.jc5");
        string tmp = Path.Combine(Path.GetDirectoryName(destination)!, ".jacquard-" + Guid.NewGuid().ToString("N") + ".tmp");
        try { File.WriteAllBytes(tmp, data); File.Move(tmp, destination, true); }
        finally { if (File.Exists(tmp)) File.Delete(tmp); }
    }
}
